#!/usr/bin/env node

/**
 * Build script for lean-agentic npm package.
 *
 * dist/node.js  and dist/index.js  - CommonJS, copied from src/
 * dist/node.mjs and dist/index.mjs - ESM wrappers that load the CommonJS
 *                                    build through createRequire, so both
 *                                    module systems share one WASM instance
 * dist/web.mjs                     - ESM, copied from src/
 *
 * Diagnostics go to stderr so `node scripts/build.js` stays quiet on stdout.
 */

const fs = require('fs');
const path = require('path');

const srcDir = path.join(__dirname, '..', 'src');
const distDir = path.join(__dirname, '..', 'dist');

fs.mkdirSync(distDir, { recursive: true });

function copy(from, to) {
  fs.copyFileSync(path.join(srcDir, from), path.join(distDir, to));
  console.error(`created dist/${to}`);
}

function esmWrapper(cjsName) {
  // Load the CommonJS build to learn its export names.
  const mod = require(path.join(distDir, `${cjsName}.js`));
  const names = Object.keys(mod).sort();
  for (const name of names) {
    if (!/^[A-Za-z_$][\w$]*$/.test(name) || name === 'default') {
      throw new Error(`dist/${cjsName}.js exports an unsupported name: ${name}`);
    }
  }
  const body = [
    '// Generated by scripts/build.js. Do not edit.',
    "import { createRequire } from 'node:module';",
    '',
    'const require = createRequire(import.meta.url);',
    `const mod = require('./${cjsName}.js');`,
    '',
    `export const { ${names.join(', ')} } = mod;`,
    'export default mod;',
    ''
  ].join('\n');
  fs.writeFileSync(path.join(distDir, `${cjsName}.mjs`), body);
  console.error(`created dist/${cjsName}.mjs`);
}

copy('node.js', 'node.js');
copy('index.js', 'index.js');
copy('web.js', 'web.mjs');
esmWrapper('node');
esmWrapper('index');
